def money(value):
    return float(Decimal(str(value)).quantize(Decimal(".01"), rounding=ROUND_HALF_UP))


def nutrition(recipe_or_parts, servings=1):
    parts = recipe_or_parts["ingredients"] if isinstance(recipe_or_parts, dict) else recipe_or_parts
    total = dict(kcal=0.0, carbs=0.0, fiber=0.0, protein=0.0, fat=0.0, sodium=0.0)
    for part in parts:
        item = INGREDIENTS[part["ingredient_id"]]
        factor = part["quantity"] if item["per"] == "unid" else part["quantity"] / 100
        for k in total:
            total[k] += item["nutrients"][k] * factor
    return {
        k: round(v * servings, 1 if k not in {"kcal", "sodium"} else 0) for k, v in total.items()
    }


THRESHOLDS = {
    # per serving: (green max, yellow max)
    "carbs": {D: (45, 60), A: (60, 75), C: (50, 65)},
    "sodium": {D: (500, 800), A: (600, 900), C: (600, 900)},
    "kcal": {D: (400, 500), A: (650, 800), C: (500, 650)},
}


def _level(value, kind, metric):
    green, yellow = THRESHOLDS[metric][kind]
    return "verde" if value <= green else "amarillo" if value <= yellow else "rojo"


def traffic(recipe):
    """Semáforo por condición (referencial, por porción)."""
    n = nutrition(recipe)
    kind = recipe["kind"]
    carbs = _level(n["carbs"], kind, "carbs")
    return dict(
        diabetes=carbs,
        prediabetes=carbs,
        hipertension=_level(n["sodium"], kind, "sodium"),
        obesidad=_level(n["kcal"], kind, "kcal"),
    )


def adjustments(recipe, conditions):
    ids = {p["ingredient_id"]: p["quantity"] for p in recipe["ingredients"]}
    starches = [INGREDIENTS[i]["name"].lower() for i in ids if i in STARCH_IDS]
    notes = []
    conds = set(conditions)
    if conds & {"diabetes", "prediabetes"}:
        if starches:
            notes.append(
                "Para quien tiene "
                + ("diabetes" if "diabetes" in conds else "prediabetes")
                + f": sirve máximo ½ taza (un puño) de {', '.join(starches[:2])} y llena medio plato con verduras."
            )
        if "arroz" in ids:
            notes.append("Puedes reemplazar la mitad del arroz blanco por quinua o arroz integral.")
        if any(INGREDIENTS[i]["section"] == "Frutas" for i in ids):
            notes.append("Come la fruta entera, sin azúcar añadida; evita jugos.")
        notes.append("Acompaña con agua o infusión sin azúcar.")
    if "hipertension" in conds:
        if ids.get("sal", 0) >= 0.5:
            notes.append(
                f"Para quien tiene hipertensión: usa la mitad de sal ({money(ids['sal'] / 2)} g por porción) "
                "y da sabor con ajo, limón, culantro, comino u orégano."
            )
        if "sillao" in ids:
            notes.append("Usa sillao bajo en sodio o solo unas gotas al final.")
        if "queso-fresco" in ids:
            notes.append("Prefiere queso fresco bajo en sal.")
        if "atun" in ids:
            notes.append("Escurre y enjuaga el atún de lata para reducir su sodio.")
        if "pan-integral" in ids:
            notes.append("El pan aporta sodio: no agregues sal a lo que va dentro.")
    if "obesidad" in conds:
        if traffic(recipe)["obesidad"] != "verde":
            notes.append(
                "Para controlar peso: sirve ¾ de los carbohidratos y duplica las verduras."
            )
        if "aceite" in ids or "aceite-oliva" in ids:
            notes.append("Mide el aceite con cucharita (máximo 1 por porción).")
    return notes


def compatible(recipe, profile):
    for part in recipe["ingredients"]:
        item = INGREDIENTS[part["ingredient_id"]]
        if set(item["allergens"]) & set(profile.allergies):
            return False
        tags = set(item["tags"])
        if profile.diet == "Vegano" and ("animal" in tags or "lacteo" in tags):
            return False
        if profile.diet == "Vegetariano" and tags & {"carne", "pescado"}:
            return False
        if profile.diet == "Pescetariano" and "carne" in tags:
            return False
        words = [normalize(item["name"]), part["ingredient_id"], *item["aliases"]]
        if any(ex in word or word in ex for ex in profile.excluded for word in words):
            return False
    return True


def suitable(recipe, profile):
    """Compatible y sin semáforo rojo para ninguna condición declarada."""
    if not compatible(recipe, profile):
        return False
    light = traffic(recipe)
    return all(light[c] != "rojo" for c in getattr(profile, "health", []) or [])


def recipe_card(r, profile=None):
    conds = list(getattr(profile, "health", []) or []) if profile else []
    per = nutrition(r)
    cost = money(
        sum(p["quantity"] * INGREDIENTS[p["ingredient_id"]]["unit_price"] for p in r["ingredients"])
    )
    return dict(
        id=r["id"],
        name=r["name"],
        kind=r["kind"],
        emoji=r["emoji"],
        minutes=r["minutes"],
        tags=r["tags"],
        ingredients=[
            dict(
                ingredient_id=p["ingredient_id"],
                name=INGREDIENTS[p["ingredient_id"]]["name"],
                quantity=p["quantity"],
                unit=INGREDIENTS[p["ingredient_id"]]["unit"],
            )
            for p in r["ingredients"]
        ],
        steps=r["steps"],
        nutrition=per,
        cost_per_serving=cost,
        traffic=traffic(r),
        adjustments=adjustments(r, conds) if conds else [],
        compatible=compatible(r, profile) if profile else True,
        suitable=suitable(r, profile) if profile else True,
        source=NUTRITION_SOURCE,
    )


def meal(recipe_id, servings, day, kind, conditions=()):
    r = BY_ID[recipe_id]
    parts = []
    for part in r["ingredients"]:
        item = INGREDIENTS[part["ingredient_id"]]
        parts.append(
            dict(
                ingredient_id=part["ingredient_id"],
                name=item["name"],
                quantity=round(part["quantity"] * servings, 2),
                unit=item["unit"],
                unit_price=item["unit_price"],
                allergens=item["allergens"],
                section=item["section"],
                price_date=PRICE_DATE,
            )
        )
    return dict(
        slot=f"{day}-{kind}",
        day=day,
        kind=kind,
        recipe_id=r["id"],
        name=r["name"],
        servings=servings,
        ingredients=parts,
        steps=r["steps"],
        minutes=r["minutes"],
        emoji=r["emoji"],
        nutrition=nutrition(r),
        traffic=traffic(r),
        adjustments=adjustments(r, conditions),
        estimated=True,
        done=False,
    )
